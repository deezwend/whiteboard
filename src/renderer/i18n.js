export function t(tr, params) {
  const v = lang === 'en' ? EN[tr] : undefined;
  if (typeof v === 'function') return v(params || {});
  const s = v ?? tr;
  return params ? s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m)) : s;
}

const ATTRS = ['title', 'placeholder', 'aria-label', 'data-title'];

// Sayfadaki sabit Türkçe metinleri yerinde çevirir; baştaki/sondaki boşluklar korunur.
function translateDom(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    const key = n.nodeValue.trim();
    if (key && typeof EN[key] === 'string') n.nodeValue = n.nodeValue.replace(key, EN[key]);
  }
  for (const el of root.querySelectorAll(ATTRS.map((a) => `[${a}]`).join(','))) {
    for (const a of ATTRS) {
      const v = el.getAttribute(a);
      if (v && typeof EN[v] === 'string') el.setAttribute(a, EN[v]);
    }
  }
}

// app.js düğme ipuçlarını kendi kurulumu sırasında okuduğu için çeviri modül yüklenirken yapılır.
