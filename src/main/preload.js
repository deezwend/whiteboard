const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  loadInitial: () => ipcRenderer.invoke('board:loadInitial'),
  save: (json) => ipcRenderer.invoke('board:save', json),
  saveSync: (json) => ipcRenderer.sendSync('board:saveSync', json),
  askUnsaved: () => ipcRenderer.sendSync('board:askUnsaved'),
  saveAs: (json) => ipcRenderer.invoke('board:saveAs', json),
  open: () => ipcRenderer.invoke('board:open'),
  newBoard: () => ipcRenderer.invoke('board:new'),
  openPath: (p) => ipcRenderer.invoke('board:openPath', p),
  onOpenPath: (cb) => ipcRenderer.on('openPath', (_e, p) => cb(p)),
  checkExternal: () => ipcRenderer.invoke('board:checkExternal'),
  showFolder: () => ipcRenderer.invoke('board:showFolder'),
  listBoards: () => ipcRenderer.invoke('boards:list'),
  renameBoard: (p, name) => ipcRenderer.invoke('boards:rename', p, name),
  deleteBoard: (p) => ipcRenderer.invoke('boards:delete', p),
  openVault: () => ipcRenderer.invoke('vaults:open'),
  createVault: () => ipcRenderer.invoke('vaults:create'),
  switchVault: (dir) => ipcRenderer.invoke('vaults:switch', dir),
  removeVault: (dir) => ipcRenderer.invoke('vaults:remove', dir),
  obsidianVaults: () => ipcRenderer.invoke('obsidian:vaults'),
  obsidianPickVault: () => ipcRenderer.invoke('obsidian:pickVault'),
  obsidianSetVault: (dir) => ipcRenderer.invoke('obsidian:setVault', dir),
  obsidianNotes: (dir) => ipcRenderer.invoke('obsidian:notes', dir),
  obsidianOutline: (dir, rel) => ipcRenderer.invoke('obsidian:outline', dir, rel),
  obsidianRender: (opts) => ipcRenderer.invoke('obsidian:render', opts),
  obsidianOpen: (opts) => ipcRenderer.invoke('obsidian:open', opts),
  exportPng:(dataUrl) => ipcRenderer.invoke('export:png', dataUrl),
  exportPdf: (pages, landscape) => ipcRenderer.invoke('export:pdf', pages, landscape),
  printPages: (pages, landscape) => ipcRenderer.invoke('export:print', pages, landscape),
  renderMath: (opts) => ipcRenderer.invoke('math:render', opts),
  getTheme: () => ipcRenderer.invoke('theme:get'),
  setTheme: (mode) => ipcRenderer.invoke('theme:set', mode),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd) => cb(cmd)),
});
